import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:mobile_scanner/mobile_scanner.dart';
import '../../../../core/constants/app_colors.dart';
import '../../../../core/services/location_service.dart';
import '../../data/repositories/attendance_repository.dart';
import '../bloc/qr_scanner_bloc.dart';
import '../bloc/qr_scanner_event.dart';
import '../bloc/qr_scanner_state.dart';

class QrScannerScreen extends StatelessWidget {
  final bool isCheckOut;

  const QrScannerScreen({super.key, this.isCheckOut = false});

  @override
  Widget build(BuildContext context) {
    return BlocProvider(
      create: (context) => QrScannerBloc(
        attendanceRepository: context.read<AttendanceRepository>(),
        locationService: context.read<LocationService>(),
      )..add(QrScannerStarted()),
      child: _QrScannerView(isCheckOut: isCheckOut),
    );
  }
}

class _QrScannerView extends StatefulWidget {
  final bool isCheckOut;

  const _QrScannerView({required this.isCheckOut});

  @override
  State<_QrScannerView> createState() => _QrScannerViewState();
}

class _QrScannerViewState extends State<_QrScannerView> {
  final MobileScannerController _scannerController = MobileScannerController(
    detectionSpeed: DetectionSpeed.noDuplicates,
    facing: CameraFacing.back,
    torchEnabled: false,
  );
  bool _isProcessing = false;

  @override
  void dispose() {
    _scannerController.dispose();
    super.dispose();
  }

  void _onDetect(BarcodeCapture capture) {
    if (_isProcessing) return;

    final barcodes = capture.barcodes;
    if (barcodes.isNotEmpty) {
      final code = barcodes.first.rawValue;
      if (code != null && code.trim().isNotEmpty) {
        _isProcessing = true;
        context.read<QrScannerBloc>().add(
              QrCodeDetected(rawCode: code.trim(), isCheckOut: widget.isCheckOut),
            );
      }
    }
  }

  void _showManualInputDialog() {
    final controller = TextEditingController();

    showDialog(
      context: context,
      builder: (ctx) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
        title: const Row(
          children: [
            Icon(Icons.keyboard_alt_outlined, color: AppColors.primary),
            SizedBox(width: 10),
            Text('Manual QR Input', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
          ],
        ),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Text(
              'For emulator or desktop testing, enter or paste the QR Token generated by the Admin:',
              style: TextStyle(fontSize: 13, color: AppColors.textSecondary),
            ),
            const SizedBox(height: 16),
            TextField(
              controller: controller,
              decoration: const InputDecoration(
                labelText: 'QR Token',
                hintText: 'e.g. ATT_ABC123',
                prefixIcon: Icon(Icons.qr_code_2_rounded),
              ),
            ),
          ],
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(ctx).pop(),
            child: const Text('Cancel'),
          ),
          ElevatedButton(
            onPressed: () {
              final token = controller.text.trim();
              if (token.isNotEmpty) {
                Navigator.of(ctx).pop();
                _isProcessing = true;
                context.read<QrScannerBloc>().add(
                      QrCodeDetected(rawCode: token, isCheckOut: widget.isCheckOut),
                    );
              }
            },
            child: const Text('Submit'),
          ),
        ],
      ),
    );
  }

  void _showSuccessDialog(QrScannerSuccess successState) {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (ctx) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
        contentPadding: const EdgeInsets.all(24),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Container(
              width: 70,
              height: 70,
              decoration: const BoxDecoration(
                color: AppColors.successLight,
                shape: BoxShape.circle,
              ),
              child: const Icon(Icons.check_circle_rounded, color: AppColors.success, size: 44),
            ),
            const SizedBox(height: 16),
            Text(
              widget.isCheckOut ? 'Checked Out!' : 'Checked In!',
              style: const TextStyle(fontSize: 22, fontWeight: FontWeight.bold),
            ),
            const SizedBox(height: 8),
            Text(
              successState.message,
              textAlign: TextAlign.center,
              style: const TextStyle(color: AppColors.textSecondary, fontSize: 14),
            ),
            const SizedBox(height: 20),
            Container(
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                color: AppColors.background,
                borderRadius: BorderRadius.circular(14),
                border: Border.all(color: AppColors.border),
              ),
              child: Column(
                children: [
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      const Text('Time:', style: TextStyle(color: AppColors.textSecondary, fontSize: 13)),
                      Text(
                        widget.isCheckOut
                            ? successState.attendance.checkOutFormatted
                            : successState.attendance.checkInFormatted,
                        style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 14),
                      ),
                    ],
                  ),
                  const Divider(height: 16),
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      const Text('Status:', style: TextStyle(color: AppColors.textSecondary, fontSize: 13)),
                      Text(
                        successState.attendance.status.toUpperCase(),
                        style: TextStyle(
                          fontWeight: FontWeight.bold,
                          color: successState.attendance.isLate ? AppColors.warning : AppColors.success,
                          fontSize: 14,
                        ),
                      ),
                    ],
                  ),
                  const Divider(height: 16),
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      const Text('GPS Location:', style: TextStyle(color: AppColors.textSecondary, fontSize: 13)),
                      const SizedBox(width: 8),
                      Flexible(
                        child: Text(
                          '${successState.attendance.latitudeIn?.toStringAsFixed(4) ?? "10.0889"}, ${successState.attendance.longitudeIn?.toStringAsFixed(4) ?? "77.0595"}',
                          style: const TextStyle(fontWeight: FontWeight.w600, fontSize: 12),
                          maxLines: 1,
                          overflow: TextOverflow.ellipsis,
                          textAlign: TextAlign.end,
                        ),
                      ),
                    ],
                  ),
                ],
              ),
            ),
            const SizedBox(height: 24),
            SizedBox(
              width: double.infinity,
              child: ElevatedButton(
                onPressed: () {
                  Navigator.of(ctx).pop();
                  Navigator.of(context).pop(); // Back to home
                },
                child: const Text('Done'),
              ),
            ),
          ],
        ),
      ),
    );
  }

  void _showFailureDialog(QrScannerFailure failureState) {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (ctx) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
        contentPadding: const EdgeInsets.all(24),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Container(
              width: 70,
              height: 70,
              decoration: const BoxDecoration(
                color: AppColors.errorLight,
                shape: BoxShape.circle,
              ),
              child: const Icon(Icons.cancel_rounded, color: AppColors.error, size: 44),
            ),
            const SizedBox(height: 16),
            const Text(
              'Validation Failed',
              style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold),
            ),
            const SizedBox(height: 8),
            Text(
              failureState.message,
              textAlign: TextAlign.center,
              style: const TextStyle(color: AppColors.textSecondary, fontSize: 14),
            ),
            const SizedBox(height: 24),
            Row(
              children: [
                Expanded(
                  child: OutlinedButton(
                    onPressed: () {
                      Navigator.of(ctx).pop();
                      Navigator.of(context).pop();
                    },
                    child: const Text('Cancel'),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: ElevatedButton(
                    onPressed: () {
                      Navigator.of(ctx).pop();
                      _isProcessing = false;
                      context.read<QrScannerBloc>().add(QrScannerReset());
                    },
                    child: const Text('Try Again'),
                  ),
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return BlocConsumer<QrScannerBloc, QrScannerState>(
      listener: (context, state) {
        if (state is QrScannerSuccess) {
          _showSuccessDialog(state);
        } else if (state is QrScannerFailure) {
          _showFailureDialog(state);
        }
      },
      builder: (context, state) {
        final isValidating = state is QrScannerValidating;

        return Scaffold(
          backgroundColor: Colors.black,
          appBar: AppBar(
            backgroundColor: Colors.black,
            iconTheme: const IconThemeData(color: Colors.white),
            title: Text(
              widget.isCheckOut ? 'Scan to Check Out' : 'Scan to Check In',
              style: const TextStyle(color: Colors.white, fontSize: 18),
            ),
            actions: [
              IconButton(
                tooltip: 'Toggle Flashlight',
                icon: const Icon(Icons.flash_on_rounded, color: Colors.white),
                onPressed: () => _scannerController.toggleTorch(),
              ),
              IconButton(
                tooltip: 'Switch Camera',
                icon: const Icon(Icons.flip_camera_ios_rounded, color: Colors.white),
                onPressed: () => _scannerController.switchCamera(),
              ),
            ],
          ),
          body: Stack(
            fit: StackFit.expand,
            children: [
              // Real Camera Scanner
              MobileScanner(
                controller: _scannerController,
                onDetect: _onDetect,
                errorBuilder: (context, error, child) {
                  return Center(
                    child: Padding(
                      padding: const EdgeInsets.all(24.0),
                      child: Column(
                        mainAxisAlignment: MainAxisAlignment.center,
                        children: [
                          const Icon(Icons.camera_alt_outlined, size: 64, color: Colors.white54),
                          const SizedBox(height: 16),
                          const Text(
                            'Camera Preview Not Available on this platform',
                            textAlign: TextAlign.center,
                            style: TextStyle(color: Colors.white, fontSize: 16, fontWeight: FontWeight.bold),
                          ),
                          const SizedBox(height: 8),
                          const Text(
                            'Use the manual token input below to test QR validation with the mock backend.',
                            textAlign: TextAlign.center,
                            style: TextStyle(color: Colors.white70, fontSize: 13),
                          ),
                          const SizedBox(height: 24),
                          ElevatedButton.icon(
                            onPressed: _showManualInputDialog,
                            icon: const Icon(Icons.edit_note_rounded),
                            label: const Text('Enter QR Token Manually'),
                          ),
                        ],
                      ),
                    ),
                  );
                },
              ),

              // Scanner Overlay Guide Frame
              Center(
                child: Container(
                  width: 260,
                  height: 260,
                  decoration: BoxDecoration(
                    border: Border.all(
                      color: widget.isCheckOut ? AppColors.secondaryLight : AppColors.primaryLight,
                      width: 3,
                    ),
                    borderRadius: BorderRadius.circular(24),
                  ),
                ),
              ),

              // Bottom Overlay Info Bar
              Positioned(
                bottom: 30,
                left: 20,
                right: 20,
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Container(
                      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
                      decoration: BoxDecoration(
                        color: Colors.black.withValues(alpha: 0.75),
                        borderRadius: BorderRadius.circular(16),
                        border: Border.all(color: Colors.white24),
                      ),
                      child: Row(
                        children: [
                          const Icon(Icons.my_location_rounded, color: AppColors.success, size: 20),
                          const SizedBox(width: 10),
                          const Expanded(
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text(
                                  'GPS Tracking Active',
                                  style: TextStyle(
                                    color: Colors.white,
                                    fontSize: 13,
                                    fontWeight: FontWeight.bold,
                                  ),
                                ),
                                Text(
                                  'HQ Office: 10.0889° N, 77.0595° E',
                                  style: TextStyle(color: Colors.white70, fontSize: 11),
                                ),
                              ],
                            ),
                          ),
                          TextButton(
                            onPressed: _showManualInputDialog,
                            child: const Text('Manual Input', style: TextStyle(color: AppColors.accent)),
                          ),
                        ],
                      ),
                    ),
                  ],
                ),
              ),

              // Validating Loader Screen
              if (isValidating)
                Container(
                  color: Colors.black87,
                  child: const Center(
                    child: Column(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        CircularProgressIndicator(
                          valueColor: AlwaysStoppedAnimation<Color>(Colors.white),
                        ),
                        SizedBox(height: 20),
                        Text(
                          'Validating QR & GPS Location...',
                          style: TextStyle(color: Colors.white, fontSize: 16, fontWeight: FontWeight.w600),
                        ),
                        SizedBox(height: 6),
                        Text(
                          'Verifying session with REST API backend',
                          style: TextStyle(color: Colors.white70, fontSize: 13),
                        ),
                      ],
                    ),
                  ),
                ),
            ],
          ),
        );
      },
    );
  }
}
